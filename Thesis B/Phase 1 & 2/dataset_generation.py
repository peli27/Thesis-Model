"""
Phase 2 synthetic dataset generation.

This script generates a parameter-to-response dataset using the
physics-based simply supported beam simulator developed in Phase 1.

Each dataset row is generated by:
1. Randomly sampling beam, material, damping and loading parameters.
2. Calculating the first four natural frequencies.
3. Simulating the multi-mode response under harmonic excitation.
4. Extracting scalar response quantities for machine learning.

The resulting dataset is designed for a baseline surrogate model where:
inputs  = beam/material/loading parameters
outputs = natural frequencies and displacement response quantities
"""

import csv
import os

import numpy as np

from beam_properties import get_beam_properties
from frequency_analysis import natural_frequencies
from multi_mode_response import simulate_harmonic_beam_response


# Dataset generation settings
NUMBER_OF_MODES = 4
OBSERVATION_POINT = 0.65      # x/L, selected to match the base-paper setup
SIMULATION_TIME = 2.0         # seconds
TIME_STEP = 0.002           # seconds
RANDOM_SEED = 42


# Random parameter generation
def generate_random_beam(rng):
    """
    Randomly generates one simply supported beam configuration.

    Returns
    -------
    beam : dict
        Beam property dictionary containing L, b, h, E, rho, A and I.
    damping_ratio : float
        Modal damping ratio used in the response simulation.
    """

    beam = get_beam_properties()

    beam["L"] = rng.uniform(1.0, 3.0)          # m
    beam["b"] = rng.uniform(0.02, 0.08)        # m
    beam["h"] = rng.uniform(0.005, 0.02)       # m
    beam["E"] = rng.uniform(180e9, 220e9)      # Pa
    beam["rho"] = rng.uniform(7600, 8000)      # kg/m^3

    beam["A"] = beam["b"] * beam["h"]
    beam["I"] = beam["b"] * beam["h"] ** 3 / 12

    damping_ratio = rng.uniform(0.005, 0.05)

    return beam, damping_ratio


def generate_random_loading(rng, first_natural_frequency):
    """
    Randomly generates harmonic loading parameters.

    The excitation frequency is sampled using a frequency ratio relative to
    the first natural frequency. This makes sure the dataset includes cases
    below, near and above the first resonance region.

    Returns
    -------
    force_amplitude : float
        Uniform distributed harmonic load amplitude in N/m.
    excitation_frequency : float
        Harmonic excitation frequency in Hz.
    """

    force_amplitude = rng.uniform(0.1, 10.0)       # N/m
    frequency_ratio = rng.uniform(0.2, 2.0)        # excitation_frequency / f1
    excitation_frequency = frequency_ratio * first_natural_frequency

    return force_amplitude, excitation_frequency


# Single simulation sample
def simulate_beam_sample(rng):
    """
    Runs one beam simulation and returns one dataset row.

    The response case is damped harmonic excitation of a simply supported
    beam, reconstructed at x/L = 0.65.
    """

    beam, damping_ratio = generate_random_beam(rng)

    frequencies = natural_frequencies(beam, modes=NUMBER_OF_MODES)

    force_amplitude, excitation_frequency = generate_random_loading(
        rng,
        first_natural_frequency=frequencies[0],
    )

    t = np.arange(0.0, SIMULATION_TIME + TIME_STEP, TIME_STEP)

    response = simulate_harmonic_beam_response(
        beam=beam,
        frequencies=frequencies,
        damping_ratio=damping_ratio,
        force_amplitude=force_amplitude,
        forcing_frequency=excitation_frequency,
        t=t,
        x_position=OBSERVATION_POINT,
        number_of_modes=NUMBER_OF_MODES,
    )

    sample = {
        # Input parameters
        "L": float(beam["L"]),
        "b": float(beam["b"]),
        "h": float(beam["h"]),
        "E": float(beam["E"]),
        "rho": float(beam["rho"]),
        "damping_ratio": float(damping_ratio),
        "force_amplitude": float(force_amplitude),
        "excitation_frequency": float(excitation_frequency),

        # Fixed simulation settings recorded for documentation/reproducibility
        "observation_point": float(OBSERVATION_POINT),
        "simulation_time": float(SIMULATION_TIME),
        "time_step": float(TIME_STEP),
        "number_of_modes": int(NUMBER_OF_MODES),

        # Output quantities for surrogate modelling
        "f1": float(frequencies[0]),
        "f2": float(frequencies[1]),
        "f3": float(frequencies[2]),
        "f4": float(frequencies[3]),
        "peak_displacement": float(response["peak_displacement"]),
        "rms_displacement": float(response["rms_displacement"]),
    }

    return sample


# Dataset creation, splitting and saving
def generate_dataset(number_of_samples=5000, random_seed=RANDOM_SEED):
    """
    Generates the full synthetic dataset.

    The random seed is set here so the dataset is reproducible.
    """

    rng = np.random.default_rng(random_seed)
    data = []

    for i in range(number_of_samples):
        sample = simulate_beam_sample(rng)
        data.append(sample)

        if (i + 1) % 500 == 0:
            print(f"Generated {i + 1} samples")

    return data


def split_dataset(dataset, random_seed=RANDOM_SEED):
    """
    Splits the dataset into training, validation and test sets.

    Split ratio:
    - 70% training
    - 15% validation
    - 15% test
    """

    rng = np.random.default_rng(random_seed)
    shuffled_dataset = list(dataset)
    rng.shuffle(shuffled_dataset)

    n = len(shuffled_dataset)

    train_end = int(0.70 * n)
    validation_end = int(0.85 * n)

    train_data = shuffled_dataset[:train_end]
    validation_data = shuffled_dataset[train_end:validation_end]
    test_data = shuffled_dataset[validation_end:]

    return train_data, validation_data, test_data


def save_dataset_csv(data, filename):
    """
    Saves a dataset list of dictionaries to CSV.
    """

    columns = [
        # Inputs
        "L", "b", "h", "E", "rho", "damping_ratio",
        "force_amplitude", "excitation_frequency",

        # Recorded simulation settings
        "observation_point", "simulation_time", "time_step", "number_of_modes",

        # Outputs
        "f1", "f2", "f3", "f4",
        "peak_displacement", "rms_displacement",
    ]

    with open(filename, "w", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=columns)
        writer.writeheader()
        writer.writerows(data)


if __name__ == "__main__":

    os.makedirs("dataset", exist_ok=True)

    dataset = generate_dataset(number_of_samples=5000)

    train_data, validation_data, test_data = split_dataset(dataset)

    save_dataset_csv(dataset, "dataset/full_dataset.csv")
    save_dataset_csv(train_data, "dataset/train_dataset.csv")
    save_dataset_csv(validation_data, "dataset/validation_dataset.csv")
    save_dataset_csv(test_data, "dataset/test_dataset.csv")

    print("Dataset generation complete.")
    print(f"Full dataset: {len(dataset)} samples")
    print(f"Training dataset: {len(train_data)} samples")
    print(f"Validation dataset: {len(validation_data)} samples")
    print(f"Test dataset: {len(test_data)} samples")